"""C014_logistic_training: Fixed-step logistic regression (AsNumpy/NPU version).

Inputs are constructed on the CPU with NumPy; forward runs on the NPU and
returns named device arrays.
"""
import numpy as np
import asnumpy as ap


def build_inputs():
    rng = np.random.default_rng(314)
    x = rng.standard_normal((20, 6), dtype=np.float32)
    return {'x': x, 'xt': np.ascontiguousarray(x.T), 'y': rng.integers(0, 2, (20, 1)).astype(np.float32), 'weights': np.zeros((6, 1), dtype=np.float32)}


def forward(x, xt, y, weights):
    if isinstance(x, np.ndarray):
        x = ap.ndarray.from_numpy(x)
    if isinstance(xt, np.ndarray):
        xt = ap.ndarray.from_numpy(xt)
    if isinstance(y, np.ndarray):
        y = ap.ndarray.from_numpy(y)
    if isinstance(weights, np.ndarray):
        weights = ap.ndarray.from_numpy(weights)
    __numpilot_v_1 = ap.matmul(x, weights)
    __numpilot_v_2 = ap.clip(__numpilot_v_1, -30.0, 30.0)
    __numpilot_v_3 = ap.negative(__numpilot_v_2)
    __numpilot_v_4 = ap.exp(__numpilot_v_3)
    __numpilot_v_5 = ap.add(ap.full(__numpilot_v_4.shape, 1.0, dtype=__numpilot_v_4.dtype), __numpilot_v_4)
    __numpilot_v_6 = ap.reciprocal(__numpilot_v_5)
    __numpilot_v_7 = ap.subtract(__numpilot_v_6, y)
    __numpilot_v_8 = ap.matmul(xt, __numpilot_v_7)
    __numpilot_v_9 = ap.divide(__numpilot_v_8, ap.full(__numpilot_v_8.shape, 20.0, dtype=__numpilot_v_8.dtype))
    __numpilot_v_10 = ap.multiply(weights, ap.full(weights.shape, 0.01, dtype=weights.dtype))
    __numpilot_v_11 = ap.add(__numpilot_v_9, __numpilot_v_10)
    __numpilot_v_12 = ap.multiply(__numpilot_v_11, ap.full(__numpilot_v_11.shape, 0.2, dtype=__numpilot_v_11.dtype))
