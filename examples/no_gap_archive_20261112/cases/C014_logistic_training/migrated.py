    __numpilot_v_19 = ap.reciprocal(__numpilot_v_18)
    __numpilot_v_20 = ap.subtract(__numpilot_v_19, y)
    __numpilot_v_21 = ap.matmul(xt, __numpilot_v_20)
    __numpilot_v_22 = ap.divide(__numpilot_v_21, ap.full(__numpilot_v_21.shape, 20.0, dtype=__numpilot_v_21.dtype))
    __numpilot_v_23 = ap.multiply(__numpilot_v_13, ap.full(__numpilot_v_13.shape, 0.01, dtype=__numpilot_v_13.dtype))
    __numpilot_v_24 = ap.add(__numpilot_v_22, __numpilot_v_23)
    __numpilot_v_25 = ap.multiply(__numpilot_v_24, ap.full(__numpilot_v_24.shape, 0.2, dtype=__numpilot_v_24.dtype))
    __numpilot_v_26 = ap.subtract(__numpilot_v_13, __numpilot_v_25)
    __numpilot_v_27 = ap.matmul(x, __numpilot_v_26)
    __numpilot_v_28 = ap.clip(__numpilot_v_27, -30.0, 30.0)
