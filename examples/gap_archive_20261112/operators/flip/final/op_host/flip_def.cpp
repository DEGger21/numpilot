/*!
 * \file flip_def.cpp
 * \brief Flip operator definition for NumPy-compatible asnumpy.flip.
 *
 * Bounded draft scope: float32 ND tensors and a required scalar axis
 * attribute. Other dtypes and non-scalar axis forms must be rejected by the
 * Python/ACLNN validation layer rather than silently converted.
 */
#include "register/op_def_registry.h"

namespace ops {
class Flip : public OpDef {
public:
    explicit Flip(const char* name) : OpDef(name)
    {
        this->Input("x")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        this->Output("y")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        this->Attr("axis")
            .AttrType(REQUIRED)
            .Int();

        OpAICoreConfig aicoreConfig910B;
        aicoreConfig910B.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(false)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(true);
        this->AICore().AddConfig("ascend910b", aicoreConfig910B);
    }
};
OP_ADD(Flip);
} // namespace ops