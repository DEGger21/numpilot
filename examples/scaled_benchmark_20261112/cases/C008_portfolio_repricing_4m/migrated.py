    __numpilot_v_17 = ap.multiply(__numpilot_v_16, ap.full(__numpilot_v_16.shape, 0.5, dtype=__numpilot_v_16.dtype))
    __numpilot_v_18 = ap.multiply(spot, __numpilot_v_17)
    __numpilot_v_19 = ap.multiply(strike, __numpilot_v_13)
