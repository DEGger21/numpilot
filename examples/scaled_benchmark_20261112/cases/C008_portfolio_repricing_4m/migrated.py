    __numpilot_v_23 = ap.multiply(__numpilot_v_22, ap.full(__numpilot_v_22.shape, 0.5, dtype=__numpilot_v_22.dtype))
    __numpilot_v_24 = ap.multiply(__numpilot_v_19, __numpilot_v_23)
