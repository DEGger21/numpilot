/*!
 * \file nextafter_def.cpp
 * \brief Nextafter operator definition.
 *
 * This definition is intentionally bounded to the observed NumPy profile:
 * two float32 inputs with the same shape and one float32 output.
 * Other input dtypes are not declared and therefore must be rejected by the
 * outer AsNumpy adapter rather than silently cast.
 */

#include "register/op_def_registry.h"

namespace ops {

class Nextafter : public OpDef {
public:
    explicit Nextafter(const char* name) : OpDef(name)
    {
        this->Input("x1")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        this->Input("x2")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        this->Output("y")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        OpAICoreConfig aicoreConfig910B;
        aicoreConfig910B.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(false)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(false);
        this->AICore().AddConfig("ascend910b", aicoreConfig910B);
    }
};

OP_ADD(Nextafter);

} // namespace ops